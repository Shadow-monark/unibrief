export interface IcsEventInput {
  uid?: string;
  title: string;
  date: string; // YYYY-MM-DD
  time?: string; // e.g., "09:30 AM", "16:00", "11:59 PM"
  description?: string;
  location?: string;
  circularNo?: string;
}

function escapeIcsText(value: string): string {
  return value
    .replace(/\\/g, "\\\\")
    .replace(/\r?\n/g, "\\n")
    .replace(/;/g, "\\;")
    .replace(/,/g, "\\,");
}

function pad2(n: number): string {
  return String(n).padStart(2, "0");
}

function parseTimeTo24Hour(timeStr?: string): { hours: number; minutes: number } {
  if (!timeStr) return { hours: 9, minutes: 0 };
  const trimmed = timeStr.trim();

  const amPmMatch = trimmed.match(/^(\d{1,2})(?::(\d{2}))?\s*(AM|PM)$/i);
  if (amPmMatch) {
    let hours = Number(amPmMatch[1]);
    const minutes = Number(amPmMatch[2] ?? "0");
    const period = amPmMatch[3].toUpperCase();
    if (period === "PM" && hours < 12) hours += 12;
    if (period === "AM" && hours === 12) hours = 0;
    return {
      hours: Math.min(23, Math.max(0, hours)),
      minutes: Math.min(59, Math.max(0, minutes)),
    };
  }

  const h24Match = trimmed.match(/^(\d{1,2}):(\d{2})/);
  if (h24Match) {
    return {
      hours: Math.min(23, Math.max(0, Number(h24Match[1]))),
      minutes: Math.min(59, Math.max(0, Number(h24Match[2]))),
    };
  }

  return { hours: 9, minutes: 0 };
}

function formatIcsLocalDateTime(dateStr: string, hours: number, minutes: number): string {
  const cleanDate = dateStr.replace(/-/g, "").slice(0, 8);
  return `${cleanDate}T${pad2(hours)}${pad2(minutes)}00`;
}

function formatIcsUtcNow(): string {
  const now = new Date();
  return `${now.getUTCFullYear()}${pad2(now.getUTCMonth() + 1)}${pad2(now.getUTCDate())}T${pad2(now.getUTCHours())}${pad2(now.getUTCMinutes())}${pad2(now.getUTCSeconds())}Z`;
}

export function generateIcsContent(input: IcsEventInput): string {
  const { hours, minutes } = parseTimeTo24Hour(input.time);
  const startDate = /^\d{4}-\d{2}-\d{2}$/.test(input.date)
    ? input.date
    : "2026-12-01";

  const endMinutesTotal = hours * 60 + minutes + 30;
  const endHours = Math.min(23, Math.floor(endMinutesTotal / 60));
  const endMinutes = endHours === 23 && endMinutesTotal >= 24 * 60 ? 59 : endMinutesTotal % 60;

  const dtStart = formatIcsLocalDateTime(startDate, hours, minutes);
  const dtEnd = formatIcsLocalDateTime(startDate, endHours, endMinutes);
  const dtStamp = formatIcsUtcNow();
  const uid =
    input.uid ??
    `${startDate}-${input.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").slice(0, 28)}@unibrief.edu`;

  const descriptionLines = [
    input.circularNo ? `Official Circular: ${input.circularNo}` : null,
    input.description ?? null,
    "Generated by UniBrief Deadline Radar",
  ]
    .filter((line): line is string => Boolean(line))
    .join("\n");

  const lines = [
    "BEGIN:VCALENDAR",
    "VERSION:2.0",
    "PRODID:-//UniBrief//Campus Knowledge & Deadline Radar//EN",
    "CALSCALE:GREGORIAN",
    "METHOD:PUBLISH",
    "BEGIN:VEVENT",
    `UID:${escapeIcsText(uid)}`,
    `DTSTAMP:${dtStamp}`,
    `DTSTART:${dtStart}`,
    `DTEND:${dtEnd}`,
    `SUMMARY:${escapeIcsText(input.title)}`,
    `DESCRIPTION:${escapeIcsText(descriptionLines)}`,
    input.location ? `LOCATION:${escapeIcsText(input.location)}` : null,
    "BEGIN:VALARM",
    "TRIGGER:-P1D",
    "ACTION:DISPLAY",
    `DESCRIPTION:${escapeIcsText(`Reminder (24h): ${input.title}`)}`,
    "END:VALARM",
    "BEGIN:VALARM",
    "TRIGGER:-PT2H",
    "ACTION:DISPLAY",
    `DESCRIPTION:${escapeIcsText(`Urgent Reminder (2h): ${input.title}`)}`,
    "END:VALARM",
    "END:VEVENT",
    "END:VCALENDAR",
  ].filter((line): line is string => line !== null);

  return `${lines.join("\r\n")}\r\n`;
}

export function downloadIcsFile(input: IcsEventInput): void {
  if (typeof window === "undefined") return;
  const icsContent = generateIcsContent(input);
  const blob = new Blob([icsContent], { type: "text/calendar;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  const safeSlug = input.title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")
    .slice(0, 48);
  anchor.href = url;
  anchor.download = `${safeSlug || "campus-deadline"}.ics`;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
